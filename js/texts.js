  function copy(text, btn) {
    function done() { var o = btn.textContent; btn.textContent = tr("tx.copied"); setTimeout(function () { btn.textContent = o; }, 1600); }
    function fb() { var ta = document.createElement("textarea"); ta.value = text; ta.style.cssText = "position:fixed;opacity:0"; document.body.appendChild(ta); ta.select(); try { document.execCommand("copy"); } catch (e) {} ta.remove(); done(); }
    if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(text).then(done).catch(fb); else fb();
  }

